export function applyChoice(
  g: Game,
  index: number,
  input = '',
  source: Entry['source'] = 'choice',
  reply?: string,
): Game {
  if (
    g.phase !== 'choice' ||
    !Number.isInteger(index) ||
    index < 0 ||
    index > 2
  )
    throw new Error('当前不能做出这个选择');
  const c = chapters[g.chapter].choices[index];
  const stats = { ...g.stats };
  for (const key of Object.keys(c.effect) as (keyof Stats)[])
    stats[key] = Math.max(0, Math.min(100, stats[key] + (c.effect[key] ?? 0)));
  return {
    ...g,
    phase: 'result',
    resultLine: 0,
    stats,
    entries: [
      ...g.entries,
      {
        chapter: g.chapter,
        choice: index,
        input: input || c.label,
        response: reply || c.response,
        memory: c.memory,
        source,
      },
    ],
  };
}
export function advance(g: Game): Game {
  if (g.phase === 'story') {
    return g.line + 1 < getLines(g).length
      ? { ...g, line: g.line + 1 }
      : { ...g, phase: 'choice' };
  }
  if (g.phase === 'result') {
    if (g.resultLine === 0) return { ...g, resultLine: 1 };
    if (g.chapter === 9) return { ...g, phase: 'ending' };
    return {
      ...g,
      chapter: g.chapter + 1,
      line: 0,
      resultLine: 0,
      phase: 'story',
    };
  }
  return g;
}
export function suggest(chapter: number, text: string): number | null {
  const values = chapters[chapter].choices.map((c) =>
    c.keywords.reduce((n, k) => n + (text.includes(k) ? 1 : 0), 0),
  );
  const max = Math.max(...values);
  return max > 0 && values.filter((v) => v === max).length === 1
    ? values.indexOf(max)
    : null;
}
