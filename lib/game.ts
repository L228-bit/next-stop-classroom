export function decodeSave(raw: string): Game | null {
  try {
    const g = JSON.parse(raw);
    if (
      g.version !== 1 ||
      !Number.isInteger(g.chapter) ||
      g.chapter < 0 ||
      g.chapter > 9 ||
      !['story', 'choice', 'result', 'ending'].includes(g.phase) ||
      !Number.isInteger(g.line) ||
      g.line < 0 ||
      g.line >= chapters[g.chapter].lines.length ||
      ![0, 1].includes(g.resultLine) ||
      !Array.isArray(g.entries) ||
      !Number.isFinite(g.startedAt)
    )
      return null;
    const expected =
      g.chapter + (['result', 'ending'].includes(g.phase) ? 1 : 0);
    if (
      g.entries.length !== expected ||
      (g.phase === 'ending' && g.chapter !== 9)
    )
      return null;
    for (let i = 0; i < g.entries.length; i++) {
      const e = g.entries[i];
      if (
        e.chapter !== i ||
        !Number.isInteger(e.choice) ||
        e.choice < 0 ||
        e.choice > 2 ||
        typeof e.input !== 'string' ||
        e.input.length > 200 ||
        typeof e.response !== 'string' ||
        e.response.length > 1000 ||
        typeof e.memory !== 'string' ||
        !['choice', 'offline', 'ai'].includes(e.source)
      )
        return null;
    }
    let computed = freshGame();
    for (const e of g.entries) {
      computed = { ...computed, chapter: e.chapter, phase: 'choice' };
      computed = applyChoice(computed, e.choice, e.input, e.source, e.response);
    }
    for (const key of ['craft', 'trust', 'purpose', 'energy'])
      if (g.stats?.[key] !== computed.stats[key as keyof Stats]) return null;
    return g as Game;
  } catch {
    return null;
  }
}
